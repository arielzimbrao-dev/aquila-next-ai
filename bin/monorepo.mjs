// Projects in a subfolder of the git repository and several aquila packages in one repository.
// Contract shared by aquila-ai, aquila-react-ai and aquila-next-ai — keep it identical in the three:
//   <repo root>/.aquila-hooks/pre-commit and pre-push: one dispatcher, same bytes in every package
//     (first comment line `# aquila-hooks v<n>`; a package never downgrades a newer one);
//   <repo root>/.aquila-hooks/projects: `<folder relative to the root, or .>\t<package>` per line;
//   core.hooksPath = .aquila-hooks (git resolves a relative hooksPath from the repository root).
// The dispatcher is per clone (each dev runs init), so it is excluded from git like the local adapters.
import { chmodSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const DISPATCH_DIR = '.aquila-hooks';
const VERSION = 1;
const MARK = /^# aquila-hooks v(\d+)/m;

// POSIX sh: Git for Windows runs hooks with its bundled sh. The phase is the file name.
export const DISPATCHER = `#!/bin/sh
# aquila-hooks v${VERSION} — git hooks dispatcher shared by aquila-ai, aquila-react-ai and aquila-next-ai.
# Generated by \`npx <package> init\`; do not edit. Projects: .aquila-hooks/projects (<folder><TAB><package>).
# Runs \`<package> gate <phase>\` inside each project whose folder has changes in this commit/push.
phase=$(basename "$0")
top=$(git rev-parse --show-toplevel) || exit 1
list="$top/.aquila-hooks/projects"
[ -f "$list" ] || exit 0
all=0
changed=
if [ "$phase" = pre-push ]; then
  while read -r lref lsha rref rsha; do
    case "$lsha" in *[!0]*) ;; *) continue ;; esac
    case "$rsha" in
      *[!0]*) files=$(git diff --name-only "$rsha" "$lsha" 2>/dev/null) || all=1
        changed="$changed
$files" ;;
      *) all=1 ;;
    esac
  done
else
  changed=$(git diff --cached --name-only)
fi
status=0
tab=$(printf '\\t')
while IFS="$tab" read -r dir pkg; do
  case "$dir" in '' | '#'*) continue ;; esac
  if [ "$all" = 0 ]; then
    if [ "$dir" = . ]; then
      printf '%s\\n' "$changed" | grep -q . || continue
    else
      re=$(printf '%s' "$dir" | sed 's/[][\\.*^$]/\\\\&/g')
      if ! printf '%s\\n' "$changed" | grep -q "^$re/"; then
        echo "↷ aquila: $dir — no changes, $phase skipped"
        continue
      fi
    fi
  fi
  bin="$top/$dir/node_modules/$pkg/bin/aquila.mjs"
  if [ ! -f "$bin" ]; then
    echo "✗ aquila: $dir/node_modules/$pkg/bin/aquila.mjs not found — install the dependencies in $dir" >&2
    status=1
    continue
  fi
  echo "▶ aquila: $dir ($pkg) gate $phase"
  (cd "$top/$dir" && node "$bin" gate "$phase" </dev/null) || status=1
done < "$list"
exit $status
`;

const PHASES = ['pre-commit', 'pre-push'];
const posix = (path) => path.split('\\').join('/');

/** { top, prefix } of the git repository (prefix `backend/` or ''), or null outside git. */
export function repoInfo(git) {
  const top = git('rev-parse', '--show-toplevel');
  return top ? { top, prefix: git('rev-parse', '--show-prefix') } : null;
}

/** Folder of the project in the registry: relative to the repository root, `.` at the root. */
export const projectDir = (prefix) => (prefix ? prefix.replace(/\/+$/, '') : '.');

/** CI workflow path relative to the repository root: one per project when it lives in a subfolder. */
export const workflowPath = (prefix) =>
  prefix
    ? `.github/workflows/aquila-gates-${projectDir(prefix).replace(/[^\w.-]+/g, '-')}.yml`
    : '.github/workflows/aquila-gates.yml';

export function readRegistry(top) {
  const file = join(top, DISPATCH_DIR, 'projects');
  if (!existsSync(file)) return [];
  return readFileSync(file, 'utf8')
    .split(/\r?\n/)
    .filter((line) => line.trim() && !line.startsWith('#'))
    .map((line) => line.split('\t'));
}

/** Adds or updates `dir → pkg`, keeping the other projects and their order. Returns true if it changed. */
export function register(top, dir, pkg) {
  const entries = readRegistry(top);
  const index = entries.findIndex(([d]) => d === dir);
  if (index >= 0 && entries[index][1] === pkg) return false;
  if (index >= 0) entries[index] = [dir, pkg];
  else entries.push([dir, pkg]);
  mkdirSync(join(top, DISPATCH_DIR), { recursive: true });
  writeFileSync(join(top, DISPATCH_DIR, 'projects'), entries.map((e) => `${e.join('\t')}\n`).join(''));
  return true;
}

/** Writes the dispatcher unless a newer version is already there. Returns true if it changed. */
export function writeDispatcher(top) {
  let changed = false;
  for (const phase of PHASES) {
    const file = join(top, DISPATCH_DIR, phase);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (Number(MARK.exec(current ?? '')?.[1] ?? 0) > VERSION) continue;
    if (current !== DISPATCHER) {
      mkdirSync(join(top, DISPATCH_DIR), { recursive: true });
      writeFileSync(file, DISPATCHER);
      changed = true;
    }
    chmodSync(file, 0o755);
  }
  return changed;
}

/**
 * Project folder whose aquila hooks a core.hooksPath runs (`.` for the root), or null when it is not an
 * aquila per-project hooks path (husky, dispatcher, custom).
 */
export function aquilaHooksOwner(hooksPath) {
  const path = posix(hooksPath ?? '').replace(/\/+$/, '');
  const method = /^(?:(.+)\/)?\.aquila\/githooks$/.exec(path);
  if (method) return method[1] ?? '.';
  return /^node_modules\/aquila[\w-]*\/githooks$/.test(path) ? '.' : null;
}

/** Package that the per-project hooks of `dir` call (to register a project migrated to the dispatcher). */
export function hookPackage(top, dir) {
  const file = join(top, dir, '.aquila', 'githooks', 'pre-commit');
  if (!existsSync(file)) return null;
  return /node_modules\/(aquila[\w-]*)\/bin\/aquila\.mjs/.exec(readFileSync(file, 'utf8'))?.[1] ?? null;
}

const executable = (file) => process.platform === 'win32' || (statSync(file).mode & 0o111) !== 0;

/** Why the configured hooks don't run this project's gates (empty when they do). */
export function hookSetupIssues({ top, prefix, hooksPath, pkg }) {
  const dir = projectDir(prefix);
  const fix = `npx ${pkg} init`;
  const issues = [];
  const path = posix(hooksPath ?? '').replace(/\/+$/, '');
  if (path === DISPATCH_DIR) {
    for (const phase of PHASES) {
      const file = join(top, DISPATCH_DIR, phase);
      const name = `${DISPATCH_DIR}/${phase}`;
      if (!existsSync(file)) issues.push(`${name} missing → ${fix}`);
      else if (!MARK.test(readFileSync(file, 'utf8')))
        issues.push(`${name} is not the aquila dispatcher → ${fix}`);
      else if (!executable(file)) issues.push(`${name} is not executable → ${fix} (or chmod +x)`);
    }
    const entries = readRegistry(top);
    if (!entries.some(([d]) => d === dir))
      issues.push(`${dir} is not registered in ${DISPATCH_DIR}/projects → ${fix}`);
    for (const [d, p] of entries) {
      if (!p || !existsSync(join(top, d, 'node_modules', p, 'bin', 'aquila.mjs')))
        issues.push(
          `the dispatcher cannot find ${d}/node_modules/${p}/bin/aquila.mjs → install the dependencies in ${d}`,
        );
    }
    return issues;
  }
  const owner = aquilaHooksOwner(path);
  if (owner === null) return issues;
  if (owner !== dir) {
    issues.push(
      owner === '.' && prefix
        ? `core.hooksPath ${path} resolves from the repository root (${posix(top)}), not from ${prefix} — this project's gates never run → ${fix} (shared dispatcher)`
        : `core.hooksPath ${path} runs the hooks of ${owner}, not of ${dir} → ${fix} (shared dispatcher)`,
    );
    return issues;
  }
  for (const phase of PHASES) {
    const file = join(top, path, phase);
    if (!existsSync(file)) issues.push(`${path}/${phase} missing → ${fix}`);
    else if (!executable(file)) issues.push(`${path}/${phase} is not executable → ${fix}`);
  }
  return issues;
}
